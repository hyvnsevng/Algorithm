WITH G AS (
    SELECT SUM(SCORE) AS SCORE, EMP_NO
    FROM HR_GRADE
    GROUP BY EMP_NO
)

SELECT A.SCORE, A.EMP_NO, A.EMP_NAME, A.POSITION, A.EMAIL
FROM (
    SELECT RANK() OVER (ORDER BY G.SCORE DESC) AS RNK,
        G.SCORE, E.EMP_NO, E.EMP_NAME, E.POSITION, E.EMAIL
    FROM HR_EMPLOYEES E
    JOIN G ON G.EMP_NO = E.EMP_NO
) A
WHERE A.RNK = 1
