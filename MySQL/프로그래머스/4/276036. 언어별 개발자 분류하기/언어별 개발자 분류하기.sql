WITH FESC AS (
    SELECT CATEGORY, SUM(CODE) AS SC
    FROM SKILLCODES
    WHERE CATEGORY = 'Front End'
)

SELECT 
    CASE
        WHEN D.SKILL_CODE & FESC.SC AND D.SKILL_CODE & (SELECT CODE FROM SKILLCODES WHERE NAME = 'Python') THEN 'A'
        WHEN D.SKILL_CODE & (SELECT CODE FROM SKILLCODES WHERE NAME = 'C#') THEN 'B'
        WHEN D.SKILL_CODE & FESC.SC THEN 'C' END
    AS GRADE, 
    ID, 
    EMAIL
FROM DEVELOPERS D
JOIN FESC ON D.SKILL_CODE & FESC.SC OR D.SKILL_CODE & (SELECT CODE FROM SKILLCODES WHERE NAME = 'C#')
ORDER BY GRADE, ID