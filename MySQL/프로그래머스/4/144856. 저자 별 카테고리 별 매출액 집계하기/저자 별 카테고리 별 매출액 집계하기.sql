SELECT SBB.AUTHOR_ID, A.AUTHOR_NAME, SBB.CATEGORY, SBB.TOTAL_SALES
FROM (
    SELECT B.CATEGORY, B.AUTHOR_ID, SUM(B.PRICE * BS.SALES) AS TOTAL_SALES
    FROM BOOK B
    JOIN BOOK_SALES BS ON B.BOOK_ID = BS.BOOK_ID
    WHERE DATE_FORMAT(SALES_DATE, "%Y-%m") = "2022-01"
    GROUP BY B.CATEGORY, B.AUTHOR_ID
) AS SBB
JOIN AUTHOR A ON A.AUTHOR_ID = SBB.AUTHOR_ID
ORDER BY SBB.AUTHOR_ID, SBB.CATEGORY DESC